// Turns design/figma-tokens.json (read from Figma via figma-cli) into Tailwind v4 theme tokens.
import { readFileSync, writeFileSync } from 'node:fs'

const t = JSON.parse(readFileSync(new URL('../design/figma-tokens.json', import.meta.url), 'utf8'))
const lines = ['/* GENERATED by scripts/sync-tokens.mjs from design/figma-tokens.json. Do not edit. */', '@theme {']
lines.push(`  --font-sans: ${t.font};`)
for (const [k, v] of Object.entries(t.colors)) lines.push(`  --color-${k}: ${v};`)
for (const [k, v] of Object.entries(t.radius)) lines.push(`  --radius-${k}: ${v};`)
for (const [k, v] of Object.entries(t.shadow)) lines.push(`  --shadow-${k}: ${v};`)
for (const [k, v] of Object.entries(t.text)) lines.push(`  --text-${k}: ${v};`)
for (const [k, v] of Object.entries(t.motion ?? {})) if (!k.startsWith('_') && k !== 'ease') lines.push(`  --duration-${k}: ${v};`)
if (t.motion?.ease) lines.push(`  --ease-out: ${t.motion.ease};`)
lines.push('}', '')
writeFileSync(new URL('../src/theme.css', import.meta.url), lines.join('\n'))
console.log(`theme.css: ${Object.keys(t.colors).length} colors, ${Object.keys(t.radius).length} radii, ${Object.keys(t.shadow).length} shadows`)
